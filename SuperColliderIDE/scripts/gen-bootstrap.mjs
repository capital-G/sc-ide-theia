import { readFile, writeFile } from "node:fs/promises";

// since we do not have fs access within a browser environment,
// we need to expose the contents of the bootstrap.scd as typescript module

const src = await readFile(
    new URL("../src/node/sc/bootstrap.scd", import.meta.url),
    "utf-8",
);
await writeFile(
    new URL("../src/common/sc-bootstrap.ts", import.meta.url),
    `// AUTO-GENERATED by scripts/gen-bootstrap.mjs - PLEASE EDIT src/node/sc/bootstrap.scd instead!\n\n` +
        `export const SC_BOOTSTRAP = ${JSON.stringify(src)};\n`,
);
